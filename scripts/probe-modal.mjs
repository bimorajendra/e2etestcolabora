import { chromium } from '@playwright/test';
import fs from 'node:fs';
const B='https://colabora.aksara.blog';
const accs=JSON.parse(fs.readFileSync('accounts.local.json','utf8'));
const b=await chromium.launch(); const p=await b.newPage({viewport:{width:1400,height:900}});
const a=accs.find(x=>x.role==='super-user');
await p.goto(B+'/login');await p.getByLabel('Email',{exact:true}).fill(a.email);await p.getByLabel('Kata sandi',{exact:true}).fill(a.password);
await p.getByRole('button',{name:'Masuk'}).click();await p.waitForURL(/dashboard/,{timeout:30000});
await p.getByRole('button',{name:'Nanti'}).click();
console.log('sessionStorage keys:',await p.evaluate(()=>Object.keys(sessionStorage)),'local:',await p.evaluate(()=>Object.keys(localStorage)));
await p.getByRole('region',{name:'Papan proses permohonan'}).getByRole('link').first().click();
await p.waitForURL(/permohonan\//);
await p.goBack();await p.waitForLoadState('networkidle').catch(()=>{});await p.waitForTimeout(1500);
console.log('modal after back (history):',await p.getByRole('alertdialog').count());
await p.goto(B+'/admin/akun');await p.getByRole('link',{name:'Beranda',exact:true}).first().click();await p.waitForTimeout(1500);
console.log('modal after sidebar Beranda:',await p.getByRole('alertdialog').count());
await b.close();
const b2=await chromium.launch(); const q=await b2.newPage();
await q.goto(B+'/registrasi');
await q.locator('input[type=file]').setInputFiles({name:'catatan.txt',mimeType:'text/plain',buffer:Buffer.from('x')});
await q.getByLabel('Nama lengkap').fill('E2E Tipe File');await q.getByLabel('Email').fill('e2e-tipefile@example.com');
await q.getByLabel('Kata sandi',{exact:true}).fill('E2ePassword123');await q.getByLabel('Konfirmasi kata sandi').fill('E2ePassword123');
const posts=[];q.on('request',r=>{if(r.method()==='POST')posts.push(r.url())});
await q.route('**/*',r=>r.request().method()==='POST'?r.abort():r.fallback());
await q.getByRole('button',{name:'Kirim registrasi'}).click();await q.waitForTimeout(1500);
console.log('txt: alerts:',await q.$$eval('[role=alert],[data-slot=form-message],p.text-destructive',e=>e.map(x=>x.textContent.trim())),'POST attempted:',posts);
console.log('dropzone text:',(await q.locator('form').innerText()).split('\n').filter(l=>/catatan|berkas|file/i.test(l)));
await b2.close();
